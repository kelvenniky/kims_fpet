"""Build RESULTS.md from every pilot summary.json saved locally.

Usage: python3 make_results_table.py   (run from the repo root after saving a new summary)
"""
import collections
import datetime
import glob
import json
import statistics as st

DATASETS = ["cifar", "dtd", "smallnorb_azi", "dsprites_loc"]
RUNS = ["adaptformer", "fpet-r2", "mcpet-r2", "fpet-r4", "mcpet-r4"]
SEEDS = [0, 1, 2]

acc = collections.defaultdict(dict)   # (dataset, run) -> {seed: best_acc}
info = collections.defaultdict(list)  # run -> summaries, for the cost table
for f in glob.glob("*/pilot/*/seed*/*/summary.json"):
    j = json.load(open(f))
    acc[(j["dataset"], j["run"])][j["seed"]] = j["best_acc"]
    info[j["run"]].append(j)


def mean_std(v):
    if not v:
        return ""
    if len(v) == 1:
        return f"{v[0]:.2f} (1 seed)"
    return f"{st.mean(v):.2f} ± {st.stdev(v):.2f}"


def gains(dataset, r):
    a, b = acc[(dataset, f"fpet-r{r}")], acc[(dataset, f"mcpet-r{r}")]
    return [b[s] - a[s] for s in sorted(a) if s in b]


out = ["# MC-FPET pilot results", "",
       f"Generated by `make_results_table.py` on {datetime.date.today()}. "
       "Top-1 accuracy (%) on VTAB-1k, ViT-B/16 + AdaptFormer (dim 8). "
       "dsprites_loc runs after adaptformer use `--eval_every 25 --no_full_eval` (Kaggle 12 h limit).", "",
       "## All results", "",
       "| Dataset | Run | Seed 0 | Seed 1 | Seed 2 | Mean ± std |",
       "|---|---|---|---|---|---|"]
missing = []
for ds in DATASETS:
    for i, run in enumerate(RUNS):
        v = acc[(ds, run)]
        cells = []
        for s in SEEDS:
            if s in v:
                cells.append(f"{v[s]:.2f}")
            else:
                cells.append("–")
                missing.append(f"{ds} {run} seed {s}")
        out.append(f"| {ds if i == 0 else ''} | {run} | " + " | ".join(cells) + f" | {mean_std(list(v.values()))} |")

out += ["", "## MC-FPET minus FPET (same seed)", "",
        "| Dataset | r=2 | r=4 |", "|---|---|---|"]
allg = {2: [], 4: []}
for ds in DATASETS:
    row = []
    for r in (2, 4):
        g = gains(ds, r)
        allg[r] += g
        row.append(", ".join(f"{x:+.2f}" for x in g) or "pending")
    out.append(f"| {ds} | {row[0]} | {row[1]} |")
summ = [f"**{st.mean(g):+.2f} mean, {sum(x > 0 for x in g)} of {len(g)} positive**" if g else "" for g in allg.values()]
out.append(f"| **Overall** | {summ[0]} | {summ[1]} |")

out += ["", "## Accuracy relative to unmerged AdaptFormer (mean over available seeds)", "",
        "| Dataset | FPET-r2 | MC-FPET-r2 | FPET-r4 | MC-FPET-r4 |", "|---|---|---|---|---|"]
for ds in DATASETS:
    base = list(acc[(ds, "adaptformer")].values())
    cells = []
    for run in RUNS[1:]:
        v = list(acc[(ds, run)].values())
        cells.append(f"{st.mean(v) - st.mean(base):+.2f}" if v and base else "pending")
    out.append(f"| {ds} | " + " | ".join(cells) + " |")

out += ["", "## Cost (averaged over all saved runs)", "",
        "| Run | GFLOPs | Peak train memory (GB) | Train time (s, mean) |", "|---|---|---|---|"]
for run in RUNS:
    js = info[run]
    if js:
        out.append(f"| {run} | {st.mean(j['gflops'] for j in js):.1f} | "
                   f"{st.mean(j['peak_train_mem_gb'] for j in js):.2f} | "
                   f"{st.mean(j['total_train_time_s'] for j in js):.0f} |")

n = sum(len(v) for v in acc.values())
out += ["", f"## Still missing ({len(missing)} of {n + len(missing)} runs)", ""]
out += [f"- {m}" for m in missing] or ["- none"]

open("RESULTS.md", "w").write("\n".join(out) + "\n")
print(f"wrote RESULTS.md ({n} results, {len(missing)} missing)")
